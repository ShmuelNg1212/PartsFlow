// Renders the synthetic sample invoices (plan T5.1) and writes the demo extractor's prepared results (T4.2).
// Usage: node scripts/make-sample-invoices.mjs
// Output: public/samples/*.png|pdf and supabase/functions/_shared/extraction/demo-fixtures.ts
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import Decimal from 'decimal.js'
import { chromium } from '@playwright/test'
import { DEMO_SHOP, SAMPLE_INVOICES } from './demo-data.mjs'

const OUT = 'public/samples'
mkdirSync(OUT, { recursive: true })

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c])
const money = (d) => new Decimal(d).toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, ',')

function html(inv) {
  const rows = inv.lines.map((l) => ({ ...l, amount: new Decimal(l.qty).times(l.price).toFixed(2) }))
  const total = rows.reduce((s, r) => s.plus(r.amount), new Decimal(0)).toFixed(2)
  return `<!doctype html><html><head><meta charset="utf-8"><style>
    body { font-family: 'Courier New', monospace; margin: 0; padding: 36px 44px; width: 760px; color: #222; background: #fff; }
    .stamp { border: 3px solid #b00; color: #b00; font: bold 22px Arial, sans-serif; padding: 6px 14px; display: inline-block; transform: rotate(-4deg); }
    h1 { font: bold 26px Arial, sans-serif; margin: 18px 0 2px; }
    .muted { color: #555; font-size: 13px; }
    table { width: 100%; border-collapse: collapse; margin-top: 22px; font-size: 14px; }
    th, td { border-bottom: 1px solid #999; padding: 6px 4px; text-align: left; }
    td.n, th.n { text-align: right; }
    .meta { display: flex; justify-content: space-between; margin-top: 16px; font-size: 14px; }
    .total { text-align: right; font: bold 18px Arial, sans-serif; margin-top: 14px; }
    .foot { margin-top: 28px; font-size: 12px; color: #b00; }
  </style></head><body>
    <div class="stamp">SAMPLE – SYNTHETIC</div>
    <h1>${esc(inv.supplier.replace(' (synthetic)', '').toUpperCase())}</h1>
    <div class="muted">Invented supplier for PartsFlow demonstrations. Not a real business. Not a tax document.</div>
    <div class="meta">
      <div>SOLD TO: ${esc(DEMO_SHOP.name)}</div>
      <div>INVOICE NO: <b>${esc(inv.number)}</b><br>DATE: ${esc(inv.date)}</div>
    </div>
    <table><thead><tr><th>Description</th><th>Part no.</th><th class="n">Qty</th><th>Unit</th><th class="n">Unit price</th><th class="n">Amount</th></tr></thead><tbody>
      ${rows.map((r) => `<tr><td>${esc(r.wording)}</td><td>${esc(r.part)}</td><td class="n">${esc(r.qty)}</td><td>${esc(r.unit)}</td><td class="n">${money(r.price)}</td><td class="n">${money(r.amount)}</td></tr>`).join('')}
    </tbody></table>
    <div class="total">TOTAL PHP ${money(total)}</div>
    <div class="foot">SAMPLE – SYNTHETIC. Generated by scripts/make-sample-invoices.mjs.</div>
  </body></html>`
}

function field(value, confidence, override) {
  const o = override ?? {}
  return { value: 'value' in o ? o.value : value, confidence: 'value' in o && o.value === null ? null : (o.confidence ?? confidence) }
}

function prepared(inv) {
  const read = inv.read ?? {}
  const lines = inv.lines.map((l) => {
    const r = l.read ?? {}
    const amount = new Decimal(l.qty).times(l.price).toFixed(2)
    return {
      description: field(l.wording, 0.93, r.description),
      part_number: field(l.part, 0.9, r.part_number),
      quantity: field(l.qty, 0.95, r.quantity),
      unit: field(l.unit, 0.88, r.unit),
      unit_price: field(new Decimal(l.price).toFixed(2), 0.92, r.unit_price),
      discount: { value: null, confidence: null },
      amount: field(amount, 0.93, r.amount),
    }
  })
  const total = inv.lines.reduce((s, l) => s.plus(new Decimal(l.qty).times(l.price)), new Decimal(0)).toFixed(2)
  return {
    status: 'done',
    provider: 'demo',
    doc_number: field(inv.number, 0.97, read.doc_number),
    doc_date: field(inv.date, 0.94, read.doc_date),
    vendor_name: field(inv.supplier, 0.9, read.vendor_name),
    customer_name: field(DEMO_SHOP.name, 0.85),
    totals: { subtotal: { value: null, confidence: null }, tax: { value: null, confidence: null }, total: field(total, 0.95), currency: 'PHP' },
    lines,
  }
}

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 848, height: 1100 }, deviceScaleFactor: 1 })
const fixtures = {}
for (const inv of SAMPLE_INVOICES) {
  await page.setContent(html(inv), { waitUntil: 'load' })
  const path = `${OUT}/${inv.file}`
  if (inv.format === 'pdf') await page.pdf({ path, format: 'A4', printBackground: true })
  else await page.screenshot({ path, fullPage: true })
  const sha = createHash('sha256').update(readFileSync(path)).digest('hex')
  fixtures[sha] = { file: inv.file, result: prepared(inv) }
  console.log(`${inv.file} ${sha}`)
}
await browser.close()

writeFileSync(
  'supabase/functions/_shared/extraction/demo-fixtures.ts',
  `// GENERATED by scripts/make-sample-invoices.mjs. Do not edit by hand.
// Prepared results for the bundled synthetic sample invoices in public/samples/, keyed by SHA-256 of the file.
// These are canned demo results, not OCR (R-EXT-4).
import type { ExtractionDone } from './types.ts'

export const DEMO_FIXTURES: Record<string, { file: string; result: ExtractionDone }> = ${JSON.stringify(fixtures)}
`,
)
